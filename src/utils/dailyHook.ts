export function getDailyHook(): string {
  const today = new Date().toISOString().split('T')[0];
  let hash = 0;
  for (let i = 0; i < today.length; i++) {
    hash = (hash * 31 + today.charCodeAt(i)) >>> 0;
  }
  return DAILY_HOOKS[hash % DAILY_HOOKS.length];
}
